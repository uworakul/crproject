const DOTS = "................................";
const v = (value: string | number | null | undefined, dots = DOTS) => (value !== null && value !== undefined && value !== "" ? String(value) : dots);

function B({ children }: { children: string }) {
  return <SafeText style={{ fontWeight: "bold" }}>{children}</SafeText>;
}

function P({ children, indent = true }: { children: React.ReactNode; indent?: boolean }) {
  return <SafeText style={{ marginBottom: 4, textIndent: indent ? 24 : 0, lineHeight: 1.6, textAlign: "justify" }}>{children}</SafeText>;
}

function companyAddress(c: NdaData["company"]) {
  const p = c.addressParts;
  if (!Object.values(p).some(Boolean)) return c.addressFallback ?? `เลขที่ ${DOTS}`;
  return [
    `เลขที่ ${v(p.houseNo, "-")}${p.floor ? ` ชั้น ${p.floor}` : ""}`,
    p.moo ? `หมู่ที่ ${p.moo}` : null,
    p.soi ? `ซอย${p.soi}` : null,
    p.road ? `ถนน${p.road}` : null,
    `ตำบล${v(p.tambon, "-")}`,
    `อำเภอ${v(p.amphoe, "-")}`,
    `จังหวัด${v(p.province, "-")}`,
    `รหัสไปรษณีย์ ${v(p.zipCode, "-")}`,
  ]
    .filter(Boolean)
    .join(" ");
}

function employeeAddress(e: NdaData["employee"]) {
  const p = e.addressParts;
  if (!Object.values(p).some(Boolean) && e.addressFallback) return `ภูมิลำเนาอยู่ ${e.addressFallback}`;
  return `ภูมิลำเนาอยู่บ้านเลขที่ ${v(p.houseNo, "..........")} หมู่ที่ ${v(p.moo, "........")} ตรอก/ซอย ${v(p.soi, "..............")} ถนน ${v(p.road, "..............")} ตำบล/แขวง ${v(p.tambon, "..............")} อำเภอ/เขต ${v(p.amphoe, "..............")} จังหวัด ${v(p.province, "..............")} รหัสไปรษณีย์ ${v(p.zipCode, ".........")}`;
}

function SignBlock({ label, name }: { label: string; name?: string }) {
  return (
    <View style={{ width: "50%", alignItems: "center", marginBottom: 18 }}>
      <SafeText>ลงชื่อ.............................................{label}</SafeText>
      <SafeText>({name ?? "............................................."})</SafeText>
      <SafeText>วันที่......................................</SafeText>
    </View>
  );
}

